// ------- 5. MÉTRICA DE COSTURA -------
// Bordas de cena = onde o número de observações muda entre vizinhos.
function mascaraCostura(obs) {
    var obsGrossa = obs.reproject({crs: 'EPSG:4326', scale: escala_metrica});
    var kernel = ee.Kernel.square({radius: largura_costura});
    var maximo = obsGrossa.reduceNeighborhood(ee.Reducer.max(), kernel);
    var minimo = obsGrossa.reduceNeighborhood(ee.Reducer.min(), kernel);
    return maximo.neq(minimo).rename('costura');
}

function gradiente(img, banda) {
    var b = img.select(banda).reproject({crs: 'EPSG:4326', scale: escala_metrica});
    var g = b.gradient();
    return g.select('x').hypot(g.select('y')).rename(banda);
}

// Razão gradiente na costura / fora da costura, por banda,
// e fração da célula com pelo menos min_obs observações.
function metricas(estacao, nomeCand) {
    var img = estacao.cands[nomeCand];
    var costura = mascaraCostura(estacao.obs);
    var bandas = cfg.metrica;

    var grads = ee.Image(bandas.map(function(b) { return gradiente(img, b); }));
    // mean().repeat(n) agrupado pela última banda (costura 0/1)
    var stats = grads.addBands(costura).reduceRegion({
        reducer: ee.Reducer.mean().repeat(bandas.length)
                    .group({groupField: bandas.length, groupName: 'costura'}),
        geometry: celula,
        scale: escala_metrica,
        maxPixels: 1e10,
        bestEffort: true,
        tileScale: 4
    });
    var grupos = ee.List(stats.get('groups'));
    var fora = ee.List(ee.Dictionary(grupos.filter(ee.Filter.eq('costura', 0)).get(0)).get('mean'));
    var naCostura = ee.List(ee.Dictionary(grupos.filter(ee.Filter.eq('costura', 1)).get(0)).get('mean'));

    var pctMinObs = estacao.obs.gte(min_obs).reduceRegion({
        reducer: ee.Reducer.mean(), geometry: celula,
        scale: escala_metrica, maxPixels: 1e10, bestEffort: true
    }).get('n_obs');

    var props = {
        periodo: PERIODO,
        celula: CELULA,
        estacao: estacao.nome,
        candidato: nomeCand,
        rotulo: estacao.nome + ' | ' + nomeCand,
        pct_pixels_obs_ge_min: pctMinObs
    };
    bandas.forEach(function(b, i) {
        props['costura_' + b] = ee.Number(naCostura.get(i)).divide(ee.Number(fora.get(i)));
    });
    return ee.Feature(null, props);
}

var tabela = ee.FeatureCollection(estacoes.map(function(est) {
    return Object.keys(est.cands).map(function(c) { return metricas(est, c); });
}).reduce(function(a, b) { return a.concat(b); }, []));

