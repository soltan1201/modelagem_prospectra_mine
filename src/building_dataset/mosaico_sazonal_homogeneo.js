// DN → radiância → reflectância TOA (de select_black_list_save_mosaicSem.js),
// só nas bandas de 'bandas_toa'; TIR segue em DN.
function radianceToTOA(imgRad, bandas_toa) {
    imgRad = ee.Image(imgRad);

    var ESUN = {
        'B01': 1848, 'B02': 1549,  'B3N': 1114,
        'B04': 225.4,'B05': 86.63, 'B06': 81.85,
        'B07': 74.85,'B08': 66.49, 'B09': 59.85
    };

    var solarElev = ee.Number(imgRad.get('SOLAR_ELEVATION'));
    var sunZen = ee.Number(90).subtract(solarElev);
    var cosz = sunZen.multiply(Math.PI / 180).cos();

    var doy = ee.Number(ee.Date(imgRad.get('system:time_start')).getRelative('day', 'year'));
    var d = ee.Number(1).subtract(
        ee.Number(0.01672).multiply(doy.multiply(2 * Math.PI / 365).cos())
    );

    var optical = bandas_toa.map(function(b) {
        var esun  = ee.Number(ESUN[b]);
        var dn    = imgRad.select(b);
        var ganho = ee.Number(imgRad.get('GAIN_COEFFICIENT_' + b));
        return dn.subtract(1).multiply(ganho)
                 .multiply(Math.PI)
                 .multiply(d.pow(2))
                 .divide(esun.multiply(cosz))
                 .updateMask(dn.gt(0))
                 .rename(b)
                 .float();
    });

    var naoSaturado = imgRad.select(VNIR).reduce(ee.Reducer.max()).lt(DN_SATURADO);
    var tir = imgRad.select(TIR).float();

    return ee.Image(optical)
                .addBands(tir.updateMask(tir.gt(0)))
                .updateMask(naoSaturado)
                .copyProperties(imgRad, imgRad.propertyNames());
}

// Máscara de nuvem/sombra (versão de select_black_list_save_mosaicSem.js),
// só com VNIR + TIR para servir aos dois períodos.
function mascaraNuvemASTER(imgToa) {
    imgToa = ee.Image(imgToa);

    var green = imgToa.select('B01');
    var red   = imgToa.select('B02');
    var nir   = imgToa.select('B3N');
    var tir10 = imgToa.select('B10');

    var solar_el_rad = ee.Number(imgToa.get('SOLAR_ELEVATION')).multiply(Math.PI / 180);
    var shadow_dist = ee.Number(2000)
        .divide(solar_el_rad.tan().max(0.1))
        .max(200)
        .min(2000);

    var visBright = green.add(red).add(nir).divide(3);
    var cloud = visBright.gt(0.19);

    // frio relativo: percentil 20 do TIR da própria cena
    var p20 = ee.Number(tir10.reduceRegion({
        reducer: ee.Reducer.percentile([20]),
        geometry: imgToa.geometry(),
        scale: 180,
        maxPixels: 1e10,
        bestEffort: true
    }).get('B10'));
    cloud = cloud.and(tir10.lt(p20));

    var pmtro_focal = {radius: raio_borda_nuvem, kernelType: 'square', units: 'meters'};
    cloud = cloud.focal_min(pmtro_focal).focal_max(pmtro_focal);

    var dark_pixels = green.lt(lim_escuro_green).and(nir.lt(lim_escuro_nir));
    var shadow = dark_pixels.and(
        cloud.focal_max({radius: shadow_dist.add(300), units: 'meters'})
    ).focal_max();

    var valid = imgToa.select(VNIR.concat(['B10'])).reduce(ee.Reducer.min()).gt(0);
    var clear = valid.and(cloud.not()).and(shadow.not());

    return imgToa.updateMask(clear)
                 .copyProperties(imgToa, imgToa.propertyNames());
}

function addSAVI(img) {
    var red = img.select('B02');
    var nir = img.select('B3N');
    var savi = nir.subtract(red).multiply(1.5)
                  .divide(nir.add(red).add(0.5))
                  .rename('SAVI');
    return img.addBands(savi);
}

// Qualidade v5 (VNIR + TIR) — só para o candidato 'quality', linha de base
function addQualityASTER_v5(img) {
    var b1  = img.select('B01');
    var b2  = img.select('B02');
    var b3n = img.select('B3N');
    var b10 = img.select('B10');

    var savi = b3n.subtract(b2).multiply(1.5).divide(b3n.add(b2).add(0.5).add(1e-6));
    var ndwi = b1.subtract(b3n).divide(b1.add(b3n).add(1e-6));
    var brightness = b1.add(b2).add(b3n).divide(3);

    var tir_score = b10.unitScale(1050, 1300).clamp(0, 1);
    var bright_up   = brightness.unitScale(0.053, 0.122).clamp(0, 1);
    var bright_down = ee.Image(1).subtract(brightness.unitScale(0.168, 0.32).clamp(0, 1));
    var savi_score = savi.unitScale(-0.1, 0.5).clamp(0, 1);
    var ndwi_score = ndwi.multiply(-1).unitScale(-0.10, 0.45).clamp(0, 1);

    var base_quality = tir_score.multiply(0.45)
                                .add(bright_up.multiply(bright_down).multiply(0.25))
                                .add(savi_score.multiply(0.15))
                                .add(ndwi_score.multiply(0.15))
                                .clamp(0, 1);

    var cc = ee.Number(img.get('CLOUDCOVER'));
    var cloud_bonus = ee.Image(1).subtract(cc.divide(80).min(1)).multiply(0.8);
    var quality = base_quality.add(cloud_bonus).add(cc.eq(0).multiply(0.3));

    return img.addBands(quality.rename('quality').float());
}

// Ajusta uma cena à referência na área em que ela tem pixel válido.
// Se a cena não tiver estatística (tudo mascarado), sai sem ajuste.
function normalizarCena(img, ref) {
    img = ee.Image(img);
    var cena = img.select(BANDAS);
    var refNaCena = ref.select(BANDAS).updateMask(cena.mask());

    var reducer = ee.Reducer.percentile([5, 50, 95]);
    var regiao = img.geometry().intersection(celula, 100);
    var pCena = cena.reduceRegion({
        reducer: reducer, geometry: regiao, scale: escala_metrica,
        maxPixels: 1e10, bestEffort: true, tileScale: 4
    });
    var pRef = refNaCena.reduceRegion({
        reducer: reducer, geometry: regiao, scale: escala_metrica,
        maxPixels: 1e10, bestEffort: true, tileScale: 4
    });

    var ganhos = [];
    var offsets = [];
    BANDAS.forEach(function(b) {
        var c5  = pCena.get(b + '_p5');
        var c50 = pCena.get(b + '_p50');
        var c95 = pCena.get(b + '_p95');
        var r5  = pRef.get(b + '_p5');
        var r50 = pRef.get(b + '_p50');
        var r95 = pRef.get(b + '_p95');

        var temStats = ee.List([c5, c50, c95, r5, r50, r95])
                         .removeAll([null]).size().eq(6);

        var ganho = ee.Number(ee.Algorithms.If(temStats,
            ee.Number(r95).subtract(r5)
              .divide(ee.Number(c95).subtract(c5).max(1e-6))
              .max(ganho_min).min(ganho_max),
            1));
        var offset = ee.Number(ee.Algorithms.If(temStats,
            ee.Number(r50).subtract(ee.Number(c50).multiply(ganho)),
            0));
        ganhos.push(ganho);
        offsets.push(offset);
    });

    var imgGanho  = ee.Image.constant(ganhos).rename(BANDAS).float();
    var imgOffset = ee.Image.constant(offsets).rename(BANDAS).float();

    return img.addBands(cena.multiply(imgGanho).add(imgOffset), null, true);
}

